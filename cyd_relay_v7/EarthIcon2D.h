static const uint8_t EARTH_EW[4][4] = {{0,2,4,2},{0,3,4,1},{0,4,4,0},{1,4,3,0}};   // trong so cot lon-2..lon+1 theo pha 1/4 texel (tong 8)
static uint8_t earthFrac = 0;                                                       // pha le cua lan quay gan nhat (0..3)
static inline int earthShift(uint32_t ms, uint32_t rev_ms) {
  uint32_t q = ((ms % rev_ms) * ((uint32_t)EARTH_TW * 4)) / rev_ms;
  earthFrac = (uint8_t)(q & 3);
  uint32_t s = q >> 2;
  return (int)((EARTH_TW - s) % EARTH_TW);
}

// Chuyen mau SEA->LAND theo do phu 0..32 (khu rang cua o bo bien, noi suy pha khi quay)
static inline void e2dRamp(uint16_t* ramp) {
  for (int k = 0; k <= 32; k++) {
    int r = (((E2D_SEA >> 11) & 31) * (32 - k) + ((E2D_LAND >> 11) & 31) * k + 16) >> 5;
    int g = (((E2D_SEA >> 5) & 63) * (32 - k) + ((E2D_LAND >> 5) & 63) * k + 16) >> 5;
    int b = ((E2D_SEA & 31) * (32 - k) + (E2D_LAND & 31) * k + 16) >> 5;
    ramp[k] = (uint16_t)((r << 11) | (g << 5) | b);
  }
}
static inline int e2dCov(const uint8_t* land, int rb, int TW, int TH, int lat, int lon) {
  const uint8_t* wc = EARTH_EW[earthFrac];
  const int yU = lat > 0 ? lat - 1 : 0, yD = lat + 1 < TH ? lat + 1 : TH - 1;
  const int ys[3] = {yU, lat, yD}; const int wy[3] = {1, 2, 1};
  int cov = 0;
  for (int j = 0; j < 3; j++) {
    const uint8_t* row = land + ys[j] * rb;
    int n = 0;
    for (int c = 0; c < 4; c++) { if (!wc[c]) continue; int x = lon + c - 2; if (x < 0) x += TW; else if (x >= TW) x -= TW; n += wc[c] * ((pgm_read_byte(row + (x >> 3)) >> (x & 7)) & 1); }
    cov += n * wy[j];                       // toi da 8*4 = 32
  }
  return cov;
}

static void earthRow2D(int y, int shift, uint16_t* out) {
  const int D = EARTH_B_D, TW = EARTH_TW;
  for (int i = 0; i < D; i++) out[i] = EARTH_KEY;
  if (y < 0 || y >= D) return;
  const int rb = TW >> 3;
  const int x0 = pgm_read_byte(EARTH_B_X0 + y), n = pgm_read_byte(EARTH_B_N + y);
  const uint16_t* L = EARTH_B_LUT + pgm_read_word(EARTH_B_OFF + y);
  uint16_t ramp[33]; e2dRamp(ramp);
  const int TH = 114;
  const int dy = 2 * y + 1 - D, dy2 = dy * dy;
  const int t1 = (D - 2) * (D - 2), t2 = (D - 4) * (D - 4);
  for (int i = 0; i < n; i++) {
    const uint16_t e = pgm_read_word(L + i);
    uint16_t c;
    if (e & 0x8000) {
      const int dx = 2 * (x0 + i) + 1 - D, q = dx * dx + dy2;
      c = q > t1 ? E2D_GLOW0 : (q > t2 ? E2D_GLOW1 : E2D_GLOW2);
    } else {
      int lon = (int)(e & 255) + shift; if (lon >= TW) lon -= TW;
      const int lat = (int)(e >> 8);
      c = ramp[e2dCov(EARTH2D_B_LAND, rb, TW, TH, lat, lon)];
    }
    out[x0 + i] = c;
  }
}
